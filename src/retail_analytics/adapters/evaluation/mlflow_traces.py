"""Read an investigation's MLflow trace for the live smoke evaluation.

Pure parsing of the span list MLflow's ``traces/batchGet`` returns: model
attempts (provider, model, outcome, tokens), the tool sequence, BigQuery jobs
and bytes, context restarts, and whether the sanitized prompt, tool
arguments and SQL are visible. Attributes and captured payloads arrive as
OTLP values (``string_value``, ``int_value``, ``kvlist_value``) or, in the
other response shape, as JSON strings; both are read.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from typing import Any

_PAYLOADS = {"mlflow.spanInputs": "inputs", "mlflow.spanOutputs": "outputs"}


def _text(value: object) -> str:
    return value if isinstance(value, str) else json.dumps(value)


def _otlp(value: Mapping[str, Any]) -> object:
    if "kvlist_value" in value:
        return {
            str(e.get("key")): _otlp(e.get("value") or {})
            for e in value["kvlist_value"].get("values", [])
        }
    return next(iter(value.values()), "") if value else ""


def span_fields(
    span: Mapping[str, Any],
) -> tuple[dict[str, str], dict[str, dict[str, str]]]:
    """(attributes as text, {"inputs"|"outputs": {key: text}})."""
    attrs: dict[str, str] = {}
    payloads: dict[str, dict[str, str]] = {}
    raw = span.get("attributes")
    if isinstance(raw, list):
        pairs = [
            (str(i.get("key")), _otlp(i.get("value") or {}))
            for i in raw
            if isinstance(i, dict)
        ]
    elif isinstance(raw, dict):
        pairs = []
        for key, value in raw.items():
            try:
                pairs.append((str(key), json.loads(value)))
            except (TypeError, ValueError):
                pairs.append((str(key), value))
    else:
        pairs = []
    for key, value in pairs:
        if key in _PAYLOADS:
            side = value if isinstance(value, dict) else {"_": value}
            payloads[_PAYLOADS[key]] = {str(k): _text(v) for k, v in side.items()}
        else:
            attrs[key] = _text(value)
    return attrs, payloads


def _start(span: Mapping[str, Any]) -> int:
    value = span.get("start_time_unix_nano") or span.get("start_time") or 0
    try:
        return int(value)
    except (TypeError, ValueError):
        return 0


def _int(value: str | None) -> int:
    try:
        return int(value or 0)
    except ValueError:
        return 0


def trace_facts(spans: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Counts, providers, tools, jobs and content visibility of one trace."""
    attempts: list[dict[str, Any]] = []
    tools: list[str] = []
    jobs: list[dict[str, Any]] = []
    sql: list[str] = []
    restarts: list[str] = []
    visible = {"prompt": False, "tool_arguments": False, "sql": False}
    for span in sorted(spans, key=_start):
        name = str(span.get("name"))
        attrs, payloads = span_fields(span)
        if name == "model.attempt":
            attempts.append(
                {
                    "provider": attrs.get("provider", "unknown"),
                    "model": attrs.get("model", "unknown"),
                    "outcome": attrs.get("outcome", "unknown"),
                    "input_tokens": _int(attrs.get("input_tokens")),
                    "output_tokens": _int(attrs.get("output_tokens")),
                    "fallback_from": attrs.get("fallback_from", "none"),
                }
            )
            visible["prompt"] |= bool(payloads.get("inputs"))
        elif name == "tool.call":
            tools.append(attrs.get("capability", "unknown"))
            visible["tool_arguments"] |= bool(payloads.get("inputs"))
        elif name == "query.execute":
            jobs.append(
                {
                    "job_id": attrs.get("job_id"),
                    "outcome": attrs.get("outcome"),
                    "bytes_billed": attrs.get("bytes_billed"),
                    "bytes_processed": attrs.get("bytes_processed"),
                }
            )
        elif name == "query.compile":
            generated = payloads.get("inputs", {}).get("generated_sql", "")
            executed = payloads.get("outputs", {}).get("executed_sql", "")
            visible["sql"] |= bool(generated or executed)
            if generated or executed:
                sql.append(
                    f"-- generated by the model ({attrs.get('outcome', 'compiled')})\n"
                    f"{generated}\n-- executed\n{executed or '(not executed)'}"
                )
        elif name == "investigation.context_restart":
            restarts.append(attrs.get("restart.cause", "unknown"))
    ok = [a for a in attempts if a["outcome"] == "succeeded"]
    return {
        "spans": len(spans),
        "attempts": attempts,
        "model_requests": len(attempts),
        "input_tokens": sum(a["input_tokens"] for a in ok),
        "output_tokens": sum(a["output_tokens"] for a in ok),
        "tools": tools,
        "queries": sum(t == "execute_analysis" for t in tools),
        "jobs": jobs,
        "restarts": restarts,
        "content_visible": visible,
        "sql": sql,
    }


__all__ = ["span_fields", "trace_facts"]
